const assert=require('node:assert/strict');
const M=require('../../web/modules/custom/lit_map/js/bubble-model.js');
const fs=require('node:fs');
const dir='web/modules/custom/lit_map/data/';
const refs=JSON.parse(fs.readFileSync(dir+'survey-statewide-references.json'));
const data={...refs,counties:JSON.parse(fs.readFileSync(dir+'nj-counties.json')).counties};
let checks=0;
const check=(condition)=>{assert(condition);checks++;};
let s=M.read('https://example.test/?lit_lang=bad&lit_lang=es&lit_lang=en&lit_active=bad&lit_county=34003&lit_municipality=m3400141370&lit_breakdown=1&campaign=qa#map',data);
check(s.active===refs.languages.find(l=>['en','es'].includes(l.id)).id);
check(s.municipality===''&&s.county==='34003'&&s.level==='municipality');
check(s.languages.length===2);
let u=M.write('https://example.test/?campaign=qa#map',s);
check(u.searchParams.get('campaign')==='qa'&&u.hash==='#map');
assert.deepEqual(M.read(u,data),s);checks++;
check(M.normalize({...s,breakdown:false,municipality:refs.municipalities[0].id},data).municipality==='');
check(M.normalize({...s,level:'usa'},data).county==='');
check(M.normalize({...s,languages:[]},data).active==='');
check(M.normalize({...s,county:'bad'},data).level==='nj');
check(M.radius(undefined,false)===null&&M.radius(0,false)===4);
check(M.radius(1,false)===5&&M.radius(999999,false)===32);
check(Math.abs((M.radius(1600,false)/M.radius(400,false))**2-4)<1e-10);
check(Math.abs((M.radius(100,true)/M.radius(25,true))**2-4)<1e-10);
const b=[0,0,100,200];
assert.deepEqual(M.clamp([-500,900,20,40],b),[0,160,20,40]);checks++;
check(M.zoom(b,b,999)[2]===12.5);
assert.deepEqual(M.zoom(b,b,.1),b);checks++;
console.log(`${checks} bubble model checks passed.`);
